/** @file
  XenonBoot - tiny EDK2 UEFI application for SM8750 / Snapdragon 8 Elite bring-up.

  Responsibilities:
    1. Publish the embedded SM8750 ACPI tables through EFI_ACPI_TABLE_PROTOCOL.
       EFI_ACPI_TABLE_PROTOCOL installs the tables into the firmware ACPI table
       list and updates the ACPI entries exposed through EFI_SYSTEM_TABLE.
    2. Chainload Windows Boot Manager from the ESP path:
       \EFI\Microsoft\Boot\bootmgfw.efi

  Notes:
    - This application does not replace the firmware memory map. ABL/UEFI still
      owns DRAM discovery (12 GB on the target device) and Windows reads that
      from UEFI GetMemoryMap().
    - Build this module for AARCH64 and arrange for ABL/UEFI to launch it before
      Android boot, or place the resulting EFI binary at the path your firmware
      already loads.
**/

